package me.knighthat.kreate.database.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import me.knighthat.kreate.database.model.Origin
import kotlin.time.Instant

/**
 * A playlist owned by one user. Use `0` for [playlistId] on insert, Room assigns the real id.
 *
 * @property playlistId id of the playlist, generated by Room
 * @property userId owner of the playlist
 * @property origin where the playlist comes from
 * @property name name chosen by the user, a playlist always has one
 * @property thumbnail image of the playlist, `null` for none
 * @property isMonthly whether this is a monthly playlist
 * @property createdAt when the playlist was first stored
 * @property updatedAt when the playlist was last changed
 */
@Entity(
    tableName = "user_playlist",
    foreignKeys = [
        ForeignKey(
            entity = UserEntity::class,
            parentColumns = ["id"],
            childColumns = ["user_id"],
            onDelete = ForeignKey.CASCADE,
        ),
    ],
    indices = [Index("user_id")],
)
internal data class UserPlaylistEntity(
    @PrimaryKey(autoGenerate = true)
    @ColumnInfo(name = "playlist_id")
    val playlistId: Long = 0,
    @ColumnInfo(name = "user_id")
    val userId: String,
    val origin: Origin,
    val name: String,
    val thumbnail: String? = null,
    @ColumnInfo(name = "is_monthly", defaultValue = "0")
    val isMonthly: Boolean = false,
    @ColumnInfo(name = "created_at")
    val createdAt: Instant,
    @ColumnInfo(name = "updated_at")
    val updatedAt: Instant,
)
