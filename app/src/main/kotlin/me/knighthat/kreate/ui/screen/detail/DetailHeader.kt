package me.knighthat.kreate.ui.screen.detail

import android.net.Uri
import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.layout.size
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Shape
import androidx.compose.ui.text.style.TextAlign
import androidx.compose.ui.unit.dp
import me.knighthat.kreate.ui.component.Thumbnail

/**
 * The top of a detail screen: a large picture and a line under it, centered. The top bar already
 * shows the name, [title] is only for the letter on the picture while it has none.
 */
@Composable
fun DetailHeader(
    uri: Uri?,
    title: String?,
    subtitle: String?,
    shape: Shape,
    modifier: Modifier = Modifier,
) {
    Column(
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.spacedBy(4.dp),
        modifier = modifier
            .fillMaxWidth()
            .padding(16.dp),
    ) {
        Thumbnail(
            uri = uri,
            title = title,
            shape = shape,
            modifier = Modifier
                .padding(bottom = 12.dp)
                .size(200.dp),
        )
        subtitle?.let {
            Text(
                text = it,
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                textAlign = TextAlign.Center,
            )
        }
    }
}
